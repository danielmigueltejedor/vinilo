import Foundation
import Testing

@testable import ViniloKit

@Suite("Music sources")
struct SourceTests {
    private func scratch() throws -> SourceConfig {
        let directory = FileManager.default.temporaryDirectory
            .appendingPathComponent("vinilo-sources-\(UUID().uuidString)")
        return SourceConfig(directory: directory)
    }

    @Test("the ids are the ones provider.rs reads")
    func ids() {
        #expect(MusicSource.allCases.map(\.rawValue) == [
            "apple-music", "local", "spotify", "youtube-music", "tidal",
        ])
    }

    @Test("the folder follows XDG_CONFIG_HOME, else ~/.config, named after the edition")
    func folder() {
        let xdg = SourceConfig(edition: .native, environment: ["XDG_CONFIG_HOME": "/x", "HOME": "/h"])
        #expect(xdg?.directory.path == "/x/vinilo-native")
        let home = SourceConfig(edition: .native, environment: ["HOME": "/h"])
        #expect(home?.directory.path == "/h/.config/vinilo-native")
        #expect(SourceConfig(edition: .native, environment: [:]) == nil)
    }

    @Test("Apple Music until something is chosen, then what was chosen")
    func choosing() throws {
        let config = try scratch()
        #expect(config.current() == .appleMusic)
        try config.choose(.spotify)
        #expect(config.current() == .spotify)
        let text = try String(
            contentsOf: config.directory.appendingPathComponent("provider"), encoding: .utf8)
        #expect(text == "spotify\n")
    }

    @Test("a catalogue is set up once its session is saved; the others need nothing")
    func configured() throws {
        let config = try scratch()
        #expect(config.isConfigured(.appleMusic))
        #expect(config.isConfigured(.local))
        #expect(!config.isConfigured(.tidal))
        let cookie = NetscapeCookie(
            domain: ".tidal.com", hostOnly: false, path: "/", secure: true, httpOnly: true,
            expires: 1_900_000_000, name: "sid", value: "v")
        try config.saveSession([cookie], for: .tidal)
        try config.saveSession([cookie], for: .tidal)
        #expect(config.isConfigured(.tidal))
        #expect(!config.isConfigured(.spotify))
        let listed = try String(
            contentsOf: config.directory.appendingPathComponent("configured"), encoding: .utf8)
        #expect(listed == "tidal\n")
    }

    @Test("the cookie file is the one setup.rs writes")
    func netscape() {
        let file = NetscapeCookie.file([
            NetscapeCookie(
                domain: "open.spotify.com", hostOnly: true, path: "", secure: true, httpOnly: false,
                expires: 0, name: "sp_t", value: "1"),
            NetscapeCookie(
                domain: "spotify.com", hostOnly: false, path: "/", secure: true, httpOnly: true,
                expires: 42, name: "sp_dc", value: "2"),
            NetscapeCookie(
                domain: "spotify.com", hostOnly: false, path: "/", secure: true, httpOnly: false,
                expires: 0, name: "", value: "skipped"),
        ])
        #expect(
            file == "# Netscape HTTP Cookie File\n# This file was generated by Vinilo.\n"
                + "open.spotify.com\tFALSE\t/\tTRUE\t0\tsp_t\t1\n"
                + "#HttpOnly_.spotify.com\tTRUE\t/\tTRUE\t42\tsp_dc\t2\n")
    }

    @Test("signed in means the right page and the right cookie")
    func signedIn() throws {
        let player = try #require(URL(string: "https://open.spotify.com/"))
        let login = try #require(URL(string: "https://accounts.spotify.com/en/login"))
        #expect(MusicSource.spotify.looksSignedIn(url: player))
        #expect(!MusicSource.spotify.looksSignedIn(url: login))
        #expect(MusicSource.spotify.looksSignedIn(cookieNames: ["SP_DC"]))
        #expect(!MusicSource.spotify.looksSignedIn(cookieNames: ["sp_key"]))
        #expect(MusicSource.tidal.looksSignedIn(cookieNames: ["tidal_auth_token"]))
        #expect(!MusicSource.tidal.looksSignedIn(cookieNames: ["_ga_x", "csrf_token"]))
    }

    @Test("the sign-in window stays on the service and its identity providers")
    func loginNavigation() throws {
        let allowed = ["https://accounts.spotify.com/en/login", "https://accounts.google.com/o/oauth2",
            "https://appleid.apple.com/auth", "about:blank"]
        for text in allowed {
            #expect(MusicSource.spotify.allowsLoginNavigation(to: try #require(URL(string: text))), "\(text)")
        }
        let refused = ["http://accounts.spotify.com/", "https://evil.example/spotify.com",
            "https://notspotify.com/", "spotify://open", "file:///etc/passwd"]
        for text in refused {
            #expect(!MusicSource.spotify.allowsLoginNavigation(to: try #require(URL(string: text))), "\(text)")
        }
    }

    @Test("only the service's own cookies are kept")
    func cookieDomains() {
        #expect(MusicSource.spotify.ownsCookie(domain: ".open.spotify.com"))
        #expect(MusicSource.spotify.ownsCookie(domain: "spotify.com"))
        #expect(!MusicSource.spotify.ownsCookie(domain: "notspotify.com"))
        #expect(MusicSource.youtubeMusic.ownsCookie(domain: ".google.com"))
    }
}
